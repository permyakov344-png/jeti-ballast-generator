// ── ЛАТИНИЦА (передатчик не показывает кириллицу) ────────────
const TRANSLIT = {
  'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ё':'e','ж':'zh','з':'z',
  'и':'i','й':'j','к':'k','л':'l','м':'m','н':'n','о':'o','п':'p','р':'r',
  'с':'s','т':'t','у':'u','ф':'f','х':'h','ц':'c','ч':'ch','ш':'sh','щ':'sch',
  'ъ':'','ы':'y','ь':'','э':'e','ю':'ju','я':'ja',
};

const COLOR_WORDS = {
  'черный':'CHERN','чёрный':'CHERN','красный':'KRASN','белый':'BELYJ',
  'синий':'SINIJ','зеленый':'ZELEN','зелёный':'ZELEN','желтый':'ZHELT',
  'жёлтый':'ZHELT','латунь':'LATUN','сталь':'STAL',
};

function translit(s) {
  let out = '';
  for (const ch of String(s)) {
    const low = ch.toLowerCase();
    if (Object.prototype.hasOwnProperty.call(TRANSLIT, low)) {
      const rep = TRANSLIT[low];
      out += ch === low ? rep : rep.charAt(0).toUpperCase() + rep.slice(1);
    } else {
      out += ch;
    }
  }
  return out;
}

function cleanSlug(s) {
  return translit(String(s).replace(/[гГ]/g, '').trim());
}

function cleanCell(s) {
  if (s === '--' || s === '') return s;
  const key = s.trim().toLowerCase();
  if (Object.prototype.hasOwnProperty.call(COLOR_WORDS, key)) return COLOR_WORDS[key];
  return translit(s);
}

// ── LUA TEMPLATE (совпадает с tools/generate.py) ─────────────
function luaStr(s) {
  return '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

function generateLua(sh, fname) {
  const dataLines = sh.rows.map(r => '  {' + r.map(luaStr).join(', ') + '}').join(',\n');
  const slugStr = sh.slugs.map(luaStr).join(', ');
  const title = translit(sh.title);
  const rtag = "MED'";

  return `-- ${fname}.lua
-- ${title} - Ballast Table
-- Jeti DC-24 / DS-24, Lua API (setColor / drawFilledRectangle / FONT_*)
-- UP/DOWN - page, ESC - exit
-- Generated by Jeti Lua Generator

local TITLE = ${luaStr(title)}
local SLUGS = {${slugStr}}
local RTAG  = ${luaStr(rtag)}

local data = {
${dataLines}
}

local PER_PAGE = 2
local pages = {}
for i = 1, #data, PER_PAGE do pages[#pages + 1] = {i, data[i + 1] and i + 1 or nil} end
local page  = 1
local PAGES = #pages

local W, H = 320, 240
local HDR_H, COLH_H = 18, 16
local ROW_H = 97
local SUB_H = 48
local Cn  = {x = 0,   w = 36}
local Cno = {x = 36,  w = 72}
local Cw  = {x = 108, w = 70}
local Ccg = {x = 178, w = 72}
local Cv  = {x = 250, w = 70}

local function ct(col, y, h, s, font)
  local tw = lcd.getTextWidth(font, s)
  if tw > col.w - 4 then font = FONT_MINI; tw = lcd.getTextWidth(font, s) end
  lcd.drawText(col.x + (col.w - tw) // 2, y + (h - 14) // 2, s, font)
end

local function dv(y0, idx)
  local v  = data[idx]
  local y1 = y0 + SUB_H
  lcd.setColor(200, 200, 200); lcd.drawFilledRectangle(Cn.x,  y0, Cn.w,  ROW_H)
  lcd.setColor(205, 205, 205); lcd.drawFilledRectangle(Cno.x, y0, Cno.w, ROW_H)
  lcd.setColor(200, 100, 0);   lcd.drawFilledRectangle(Cw.x,  y0, Cw.w,  ROW_H)
  lcd.setColor(205, 205, 205); lcd.drawFilledRectangle(Ccg.x, y0, Ccg.w, ROW_H)
  lcd.setColor(80, 170, 0);    lcd.drawFilledRectangle(Cv.x,  y0, Cv.w,  ROW_H)
  lcd.setColor(150, 150, 150)
  lcd.drawLine(Cno.x, y1 - 1, Cno.x + Cno.w, y1 - 1)
  lcd.drawLine(Ccg.x, y1 - 1, Ccg.x + Ccg.w, y1 - 1)
  lcd.setColor(120, 120, 120)
  lcd.drawLine(Cno.x - 1, y0, Cno.x - 1, y0 + ROW_H)
  lcd.drawLine(Cw.x - 1,  y0, Cw.x - 1,  y0 + ROW_H)
  lcd.drawLine(Ccg.x - 1, y0, Ccg.x - 1, y0 + ROW_H)
  lcd.drawLine(Cv.x - 1,  y0, Cv.x - 1,  y0 + ROW_H)
  lcd.setColor(100, 100, 100)
  lcd.drawLine(0, y0 + ROW_H - 1, W, y0 + ROW_H - 1)
  lcd.setColor(10, 10, 10)
  ct(Cn,  y0, ROW_H, tostring(idx), FONT_BIG)
  ct(Cno, y0, SUB_H, v[1], FONT_BIG)
  ct(Cno, y1, SUB_H, v[2], FONT_BIG)
  ct(Cw,  y0, ROW_H, v[3], FONT_BIG)
  ct(Ccg, y0, SUB_H, v[4], FONT_BIG)
  ct(Ccg, y1, SUB_H, v[5], FONT_BIG)
  ct(Cv,  y0, ROW_H, v[6], FONT_BIG)
end

local function chdr(col, s, r, g, b)
  lcd.setColor(r, g, b)
  local tw = lcd.getTextWidth(FONT_MINI, s)
  lcd.drawText(col.x + (col.w - tw) // 2, HDR_H + 3, s, FONT_MINI)
end

local function draw()
  lcd.setColor(30, 30, 30);  lcd.drawFilledRectangle(0, 0, W, H)
  lcd.setColor(90, 90, 90);  lcd.drawFilledRectangle(0, 0, W, HDR_H)
  local x = 3
  lcd.setColor(0, 220, 255)
  local t = TITLE
  while lcd.getTextWidth(FONT_MINI, t) > 150 and #t > 4 do
    t = string.sub(t, 1, #t - 1)
  end
  lcd.drawText(x, 3, t, FONT_MINI)
  x = x + lcd.getTextWidth(FONT_MINI, t) + 4
  lcd.setColor(255, 238, 136)
  local xlim = W - lcd.getTextWidth(FONT_MINI, RTAG) - 6
  for _, s in ipairs(SLUGS) do
    local sw = lcd.getTextWidth(FONT_MINI, s)
    if x + sw > xlim then break end
    lcd.drawText(x, 3, s, FONT_MINI)
    x = x + sw + 4
  end
  lcd.setColor(255, 100, 30)
  lcd.drawText(W - lcd.getTextWidth(FONT_MINI, RTAG) - 3, 3, RTAG, FONT_MINI)

  lcd.setColor(210, 210, 210); lcd.drawFilledRectangle(0, HDR_H, W, COLH_H)
  chdr(Cn,  "No",    20, 20, 20)
  chdr(Cno, "NOS",   20, 20, 20)
  chdr(Cw,  "KRYLO", 20, 20, 20)
  chdr(Ccg, "CG",    200, 0, 0)
  chdr(Cv,  "VES",   20, 20, 20)
  lcd.setColor(120, 120, 120)
  lcd.drawLine(0, HDR_H + COLH_H - 1, W, HDR_H + COLH_H - 1)

  local p  = pages[page]
  local yd = HDR_H + COLH_H
  dv(yd, p[1])
  if p[2] then dv(yd + ROW_H, p[2]) end

  local foot = "p." .. page .. "/" .. PAGES
  lcd.setColor(100, 100, 100)
  lcd.drawText(W - lcd.getTextWidth(FONT_MINI, foot) - 3, H - 12, foot, FONT_MINI)
end

local function key(k)
  if k == KEY_UP then
    page = page - 1
    if page < 1 then page = PAGES end
  elseif k == KEY_DOWN then
    page = page + 1
    if page > PAGES then page = 1 end
  elseif k == KEY_ESC then
    system.exitScript()
  end
end

local function init()
  system.registerForm(1, MENU_APPS, TITLE, nil, key, draw)
end

return {init = init, loop = function() end, author = "Ballast", version = "1.0", name = TITLE}
`;
}

// ── EXCEL PARSER ──────────────────────────────────────────────
function asText(v) {
  if (v === null || v === undefined) return '--';
  if (typeof v === 'number') {
    if (Number.isInteger(v)) return String(v);
    return String(Math.round(v * 1000) / 1000);
  }
  const s = String(v).replace(/\u00a0/g, ' ').trim();
  return s || '--';
}

function asInt(v) {
  if (v === null || v === undefined) return null;
  if (typeof v === 'number') return Number.isInteger(v) ? v : null;
  const s = String(v).trim();
  if (/^\d+(\.0+)?$/.test(s)) return parseInt(s, 10);
  return null;
}

function cell(row, i) {
  return i < row.length ? row[i] : null;
}

function isNumeric(s) {
  return /^[\d.,]+$/.test(s);
}

function parseSheet(name, ws) {
  const data = XLSX.utils.sheet_to_json(ws, {header: 1, defval: null});
  const head = data[0] || [];

  // заголовок: из row0 берём строку с максимумом латинских букв
  let title = '';
  let best = -1;
  for (let c = 0; c < head.length; c++) {
    const t = asText(head[c]);
    if (t === '--' || isNumeric(t)) continue;
    const score = (t.match(/[A-Za-z]/g) || []).length;
    if (score > best) { best = score; title = t; }
  }
  if (!title) title = name.trim();

  // слоги + правое число (база веса) из row0
  const slugs = [];
  for (let c = 0; c < head.length; c++) {
    const t = asText(head[c]);
    if (t === '--' || isNumeric(t)) continue;
    slugs.push(t);
  }
  const slugList = slugs.filter(s => s !== title && /[\d/]/.test(s)).map(cleanSlug);

  // сдвиг правого блока: вторая колонка "№" во 2-й строке
  const hdr = data[1] || [];
  let off = 5, seen = 0;
  for (let c = 0; c < hdr.length; c++) {
    if (asText(hdr[c]).indexOf('№') === 0) {
      seen++;
      if (seen === 2) { off = c; break; }
    }
  }

  const found = {};
  for (let i = 2; i < data.length; i += 2) {
    const r1 = data[i] || [];
    const r2 = data[i + 1] || [];
    [0, off].forEach(col => {
      const num = asInt(cell(r1, col));
      if (num === null || num <= 0) return;
      found[num] = [
        asText(cell(r1, col + 1)), asText(cell(r2, col + 1)),
        asText(cell(r1, col + 2)),
        asText(cell(r1, col + 3)), asText(cell(r2, col + 3)),
        asText(cell(r1, col + 4)),
      ].map(cleanCell);
    });
  }

  const rows = Object.keys(found).map(Number).sort((a, b) => a - b).map(k => found[k]);
  return { name, title, slugs: slugList, rows };
}

function makeFileName(title) {
  let s = title.replace(/\s*20\d\d\s*$/, '');
  s = s.replace(/[^A-Za-z0-9]/g, '').toUpperCase();
  return (s || 'BALLAST').substring(0, 8);
}

// ── DOWNLOAD ──────────────────────────────────────────────────
function downloadLua(content, filename) {
  const blob = new Blob([content], {type: 'text/plain;charset=utf-8'});
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  a.click();
}

// ── STATE ─────────────────────────────────────────────────────
let parsedSheets = [];

function showStatus(msg, type) {
  const el = document.getElementById('status');
  el.textContent = msg;
  el.className = 'status show ' + (type || 'info');
}

function renderSheets() {
  const grid = document.getElementById('sheetsGrid');
  grid.innerHTML = '';
  parsedSheets.forEach((sh, idx) => {
    const auto = makeFileName(sh.title);
    const card = document.createElement('div');
    card.className = 'sheet-card';

    const previewRows = sh.rows.slice(0, 5).map((r, i) => `
      <div class="preview-row">
        <span class="preview-num">${i + 1}</span>
        <span class="preview-nos">${r[0]}/${r[1]}</span>
        <span class="preview-wing">${r[2]}</span>
        <span class="preview-cg">${r[3]}/${r[4]}</span>
        <span class="preview-ves">${r[5]}</span>
      </div>`).join('');

    card.innerHTML = `
      <div class="sheet-header">
        <span class="sheet-name">${sh.title}</span>
        <span class="sheet-badge ok">${sh.rows.length} вар.</span>
      </div>
      <div class="sheet-preview">
        <div style="color:#4a5568;margin-bottom:4px;font-size:0.65rem">НОС1/НОС2 · КРЫЛО · CG1/CG2 · ВЕС</div>
        ${previewRows}
        ${sh.rows.length > 5 ? `<div style="color:#4a5568;margin-top:4px">... ещё ${sh.rows.length - 5} вариантов</div>` : ''}
      </div>
      <div class="sheet-actions">
        <input class="fname" id="fname-${idx}" value="${auto}" maxlength="8" spellcheck="false"
               style="width:100%;margin-bottom:8px;padding:6px 8px;background:#0b0e12;color:#00c8ff;
                      border:1px solid #1e2530;border-radius:4px;font-family:'Share Tech Mono';font-size:0.85rem">
        <button class="btn-gen" onclick="generateOne(${idx})">→ ${auto}.lua</button>
        <div class="download-panel" id="dl-${idx}">
          <div class="dl-title">✓ Готово — ${auto}.lua</div>
          <a class="dl-btn" id="dlLink-${idx}">↓ Скачать</a>
          <div class="code-preview" id="codePreview-${idx}"></div>
        </div>
      </div>
    `;
    grid.appendChild(card);
  });
  document.getElementById('allBtn').className = parsedSheets.length > 1 ? 'all-btn show' : 'all-btn';
}

function generateOne(idx) {
  const sh = parsedSheets[idx];
  const inp = document.getElementById('fname-' + idx);
  let fn = makeFileName(inp && inp.value.trim() ? inp.value.trim() : sh.title);
  if (inp) inp.value = fn;

  const lua = generateLua(sh, fn);
  downloadLua(lua, fn + '.lua');

  const panel = document.getElementById('dl-' + idx);
  panel.className = 'download-panel show';
  panel.querySelector('.dl-title').textContent = '✓ Готово — ' + fn + '.lua';
  const link = document.getElementById('dlLink-' + idx);
  link.href = URL.createObjectURL(new Blob([lua], {type: 'text/plain;charset=utf-8'}));
  link.download = fn + '.lua';
  document.getElementById('codePreview-' + idx).textContent =
    lua.substring(0, 600) + '\n... (открыть файл)';
}

function generateAll() {
  parsedSheets.forEach((_, idx) => generateOne(idx));
}

// ── FILE LOAD ─────────────────────────────────────────────────
function loadFile(file) {
  showStatus('Читаю ' + file.name + '...', 'info');
  const reader = new FileReader();
  reader.onload = e => {
    try {
      const wb = XLSX.read(e.target.result, {type: 'array'});
      parsedSheets = [];
      wb.SheetNames.forEach(name => {
        const sh = parseSheet(name, wb.Sheets[name]);
        if (sh.rows.length > 0) parsedSheets.push(sh);
      });
      if (parsedSheets.length === 0) {
        showStatus('Не нашёл таблиц: нет вариантов в листах', 'err');
        return;
      }
      showStatus('Готово: ' + parsedSheets.length + ' лист(ов): ' +
        parsedSheets.map(s => s.title).join(', '), 'info');
      renderSheets();
    } catch (err) {
      showStatus('Ошибка чтения файла: ' + err.message, 'err');
    }
  };
  reader.readAsArrayBuffer(file);
}

// ── EVENTS ────────────────────────────────────────────────────
document.getElementById('fileInput').addEventListener('change', e => {
  if (e.target.files[0]) loadFile(e.target.files[0]);
});

const dz = document.getElementById('dropZone');
dz.addEventListener('dragover', e => { e.preventDefault(); dz.classList.add('drag'); });
dz.addEventListener('dragleave', () => dz.classList.remove('drag'));
dz.addEventListener('drop', e => {
  e.preventDefault();
  dz.classList.remove('drag');
  if (e.dataTransfer.files[0]) loadFile(e.dataTransfer.files[0]);
});
